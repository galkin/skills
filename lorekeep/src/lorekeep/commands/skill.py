"""`skill`: print the lorekeep skill shipped in the package, or build the folder that installs it.

The installable folder is what `npx skills add galkin/skills` copies into a repository:
`SKILL.md`, its references and `bin/lorekeep`, an entry point that runs this version of lorekeep,
with its `browser` extra, from the commit its release tag names, so a repository vendors no code
and every checkout shares one environment in uv's cache. A full commit hash, unlike a tag, is
resolved by uv without asking GitHub, so a call costs no network round trip before it runs.
Building writes only the folder it is given.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import stat
import subprocess
import sys
from importlib import metadata, resources
from importlib.resources.abc import Traversable
from pathlib import Path

REPOSITORY = "https://github.com/galkin/skills"
SUBDIRECTORY = "lorekeep"


def skill_folder() -> Traversable:
    """The skill folder inside the installed package: `SKILL.md` and its reference files."""
    return resources.files("lorekeep") / "skill"


def release_tag(version: str) -> str:
    """The git tag a version is released under in the skills repository."""
    return f"lorekeep-v{version}"


COMMIT_HASH = re.compile(r"[0-9a-f]{40}")


def release_commit(version: str) -> str | None:
    """The commit the release tag of `version` names in the git repository here, else `None`."""
    done = subprocess.run(
        ["git", "rev-parse", "--verify", "--quiet", f"{release_tag(version)}^{{commit}}"],
        capture_output=True,
        text=True,
        check=False,
    )
    found = done.stdout.strip()
    return found if done.returncode == 0 and COMMIT_HASH.fullmatch(found) else None


def entry_point(version: str, commit: str) -> str:
    """`bin/lorekeep` of the installable skill: run `version`, browser extra included, from the
    commit of its release tag."""
    source = f"lorekeep[browser] @ git+{REPOSITORY}@{commit}#subdirectory={SUBDIRECTORY}"
    return (
        "#!/bin/sh\n"
        f"# Generated by `lorekeep skill --build`: runs lorekeep {version} "
        f"({release_tag(version)}) with its browser extra.\n"
        "# uv builds it once per machine into its cache; every checkout that vendors this skill\n"
        "# shares that environment, and nothing is installed into the repository. Chromium is\n"
        "# not part of it: `lorekeep status` says when it is missing and how to install it.\n"
        f'exec uvx --quiet --from "{source}" lorekeep "$@"\n'
    )


def run(args: argparse.Namespace) -> int:
    if args.build:
        version = metadata.version("lorekeep")
        commit = args.rev or release_commit(version)
        if commit is None or not COMMIT_HASH.fullmatch(commit):
            print(
                f"lorekeep: error: no commit for {release_tag(version)}: commit the release and "
                f"tag it first, or pass --rev with a full commit hash",
                file=sys.stderr,
            )
            return 2
        return build(Path(args.build).expanduser(), version, commit)
    print((skill_folder() / "SKILL.md").read_text(encoding="utf-8"), end="")
    return 0


def build(target: Path, version: str, commit: str) -> int:
    """Replace `target` with the installable skill folder of `version`."""
    if not target.parent.is_dir():
        print(f"lorekeep: error: the folder {target.parent} does not exist", file=sys.stderr)
        return 2
    # Build beside the target first, so a failed build never leaves half a skill; the staging
    # folder is removed on any failure.
    staging = target.with_name(f"{target.name}.tmp-{os.getpid()}")
    try:
        with resources.as_file(skill_folder()) as source:
            shutil.copytree(source, staging, ignore=shutil.ignore_patterns("__pycache__"))
        script = staging / "bin" / "lorekeep"
        script.parent.mkdir()
        script.write_text(entry_point(version, commit), encoding="utf-8")
        script.chmod(script.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        if target.is_dir():
            shutil.rmtree(target)
        elif target.exists():
            target.unlink()
        staging.rename(target)
    except OSError as error:
        print(f"lorekeep: error: could not build the skill in {target}: {error}", file=sys.stderr)
        return 1
    finally:
        if staging.exists():
            shutil.rmtree(staging, ignore_errors=True)
    print(f"Built the lorekeep {version} skill in {target} from {release_tag(version)} ({commit})")
    return 0
